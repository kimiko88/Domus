// BoundingBox defines normalized coordinates [0.0 - 1.0] of a detected object.
type BoundingBox struct {
	X      float64 `json:"x"`
	Y      float64 `json:"y"`
	Width  float64 `json:"width"`
	Height float64 `json:"height"`
}

// MotionZone defines a designated area within the camera frame for motion or AI alerts.
type MotionZone struct {
	ID          string        `json:"id"`
	CameraID    string        `json:"camera_id"`
	Name        string        `json:"name"`        // e.g. "Vialetto d'ingresso", "Portico", "Parcheggio Auto"
	Coordinates []BoundingBox `json:"coordinates"` // Polygons or bounding rectangles
	Sensitivity int           `json:"sensitivity"` // 1 - 100
	Labels      []string      `json:"labels"`      // e.g. ["person", "vehicle", "package"]
	Enabled     bool          `json:"enabled"`
}

// AIDetection represents an object detected by the local computer vision model.
type AIDetection struct {
	Label           string      `json:"label"` // "person", "vehicle", "animal", "package", "face"
	Confidence      float64     `json:"confidence"` // 0.0 - 1.0
	Box             BoundingBox `json:"box"`
	Zone            string      `json:"zone,omitempty"`
	TrackID         int         `json:"track_id,omitempty"`
	PersonName      string      `json:"person_name,omitempty"`
	FaceRecognized  bool        `json:"face_recognized,omitempty"`
	LicensePlate    string      `json:"license_plate,omitempty"`
	PlateAuthorized bool        `json:"plate_authorized,omitempty"`
	Embedding       []float32   `json:"-"`
}

// NVRCameraStats holds live runtime metrics for an active camera feed.
type NVRCameraStats struct {
	CameraID       string    `json:"camera_id"`
	CameraName     string    `json:"camera_name"`
	StreamStatus   string    `json:"stream_status"` // "online", "reconnecting", "error"
	CurrentFPS     float64   `json:"current_fps"`
	BitrateKbps    int       `json:"bitrate_kbps"`
	DetectionMs    int       `json:"detection_ms"`
	TotalEvents24h int       `json:"total_events_24h"`
	LastDetection  time.Time `json:"last_detection,omitempty"`
}

// NVRSystemStatus contains aggregate metrics of the embedded NVR engine.
type NVRSystemStatus struct {
	Engine           string           `json:"engine"` // "Domus Local AI Vision"
	TotalCameras     int              `json:"total_cameras"`
	ActiveStreams    int              `json:"active_streams"`
	DetectionFPS     float64          `json:"detection_fps"`
	AverageLatencyMs int              `json:"average_latency_ms"`
	HardwareAccel    string           `json:"hardware_accel"` // "CPU / SIMD AVX2" or "GPU / OpenVINO / Apple Neural"
	StorageUsedGB    float64          `json:"storage_used_gb"`
	StorageLimitGB   float64          `json:"storage_limit_gb"`
	Cameras          []NVRCameraStats `json:"cameras"`
}

// EventClip represents an event recording snippet generated by the NVR.
type EventClip struct {
	EventID      string    `json:"event_id"`
	CameraID     string    `json:"camera_id"`
	DurationSec  float64   `json:"duration_sec"`
	ThumbnailURL string    `json:"thumbnail_url"`
	ClipURL      string    `json:"clip_url"`
	CreatedAt    time.Time `json:"created_at"`
}

// FamilyFace represents a registered family member's biometric face template.
type FamilyFace struct {
	ID         string    `json:"id"`
	Name       string    `json:"name"`
	Role       string    `json:"role,omitempty"` // e.g. "Amministratore", "Residente", "Ospite"
	PhotoURL   string    `json:"photo_url,omitempty"`
	EnrolledAt time.Time `json:"enrolled_at,omitempty"`
	Embedding  []float32 `json:"embedding,omitempty"` // e.g. 512-D or 128-D normalized face vector
}

// AuthorizedVehicle represents a resident vehicle for automatic gate/garage opening.
type AuthorizedVehicle struct {
	PlateNumber  string    `json:"plate_number"`
	OwnerName    string    `json:"owner_name"`
	VehicleModel string    `json:"vehicle_model,omitempty"`
	AutoOpenGate bool      `json:"auto_open_gate"`
	EnrolledAt   time.Time `json:"enrolled_at,omitempty"`
}

// NVRRepository defines database persistence for biometric faces, license plates, zones, and clips.
type NVRRepository interface {
	SaveFamilyFace(ctx context.Context, f FamilyFace) error
	ListFamilyFaces(ctx context.Context) ([]FamilyFace, error)
	DeleteFamilyFace(ctx context.Context, id string) error
	SaveAuthorizedPlate(ctx context.Context, v AuthorizedVehicle) error
	ListAuthorizedPlates(ctx context.Context) ([]AuthorizedVehicle, error)
	DeleteAuthorizedPlate(ctx context.Context, plate string) error
	SaveZone(ctx context.Context, z MotionZone) error
	GetZones(ctx context.Context, cameraID string) ([]MotionZone, error)
	SaveEventClip(ctx context.Context, c *EventClip) error
	GetEventClip(ctx context.Context, eventID string) (*EventClip, error)
}

// LocalNVR is the embedded computer vision engine that monitors RTSP/WebRTC streams and runs local AI inference.
type LocalNVR struct {
	mu               sync.RWMutex
	service          *Service
	bus              events.Bus
	backend          InferenceBackend
	repo             NVRRepository
	zones            map[string][]MotionZone // Keyed by cameraID
	clips            map[string]*EventClip   // Keyed by eventID
	stats            map[string]*NVRCameraStats
	familyFaces      map[string]FamilyFace
	authorizedPlates map[string]AuthorizedVehicle
}

// NewLocalNVR initializes the embedded local computer vision NVR.
func NewLocalNVR(svc *Service, bus events.Bus) *LocalNVR {
	return &LocalNVR{
		service:          svc,
		bus:              bus,
		backend:          DetectHardwareBackend(),
		zones:            make(map[string][]MotionZone),
		clips:            make(map[string]*EventClip),
		stats:            make(map[string]*NVRCameraStats),
		familyFaces:      make(map[string]FamilyFace),
		authorizedPlates: make(map[string]AuthorizedVehicle),
	}
}

// WithRepository connects the database repository and loads enrolled biometric faces and plates into cache.
func (n *LocalNVR) WithRepository(repo NVRRepository) *LocalNVR {
	n.mu.Lock()
	defer n.mu.Unlock()
	n.repo = repo
	if repo != nil {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if faces, err := repo.ListFamilyFaces(ctx); err == nil {
			for _, f := range faces {
				n.familyFaces[f.ID] = f
			}
		}
		if plates, err := repo.ListAuthorizedPlates(ctx); err == nil {
			for _, p := range plates {
				cleanPlate := strings.ToUpper(strings.ReplaceAll(p.PlateNumber, " ", ""))
				n.authorizedPlates[cleanPlate] = p
			}
		}
	}
	return n
}

// WithBackend sets a custom inference engine backend.
func (n *LocalNVR) WithBackend(b InferenceBackend) *LocalNVR {
	n.mu.Lock()
	defer n.mu.Unlock()
	n.backend = b
	return n
}

// RegisterFamilyFace enrolls a family member's biometric embedding.
func (n *LocalNVR) RegisterFamilyFace(face FamilyFace) {
	n.mu.Lock()
	if face.ID == "" {
		face.ID = "face_" + uuid.NewString()[:8]
	}
	if face.EnrolledAt.IsZero() {
		face.EnrolledAt = time.Now().UTC()
	}
	if len(face.Embedding) == 0 {
		face.Embedding = []float32{0.5, 0.5, 0.5, 0.5}
	}
	n.familyFaces[face.ID] = face
	repo := n.repo
	n.mu.Unlock()

	if repo != nil {
		_ = repo.SaveFamilyFace(context.Background(), face)
	}
}

// ListFamilyFaces returns all enrolled family member faces.
func (n *LocalNVR) ListFamilyFaces() []FamilyFace {
	n.mu.RLock()
	repo := n.repo
	if repo != nil {
		if faces, err := repo.ListFamilyFaces(context.Background()); err == nil && len(faces) > 0 {
			n.mu.RUnlock()
			return faces
		}
	}
	defer n.mu.RUnlock()
	res := make([]FamilyFace, 0, len(n.familyFaces))
	for _, f := range n.familyFaces {
		res = append(res, f)
	}
	return res
}

// RemoveFamilyFace deletes an enrolled face.
func (n *LocalNVR) RemoveFamilyFace(id string) bool {
	n.mu.Lock()
	repo := n.repo
	_, exists := n.familyFaces[id]
	if exists {
		delete(n.familyFaces, id)
	}
	n.mu.Unlock()

	if repo != nil {
		_ = repo.DeleteFamilyFace(context.Background(), id)
	}
	return exists
}

