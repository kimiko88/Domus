package handlers

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"strings"

	"github.com/domus-hub/domus/internal/domain/integration"
	"github.com/domus-hub/domus/internal/plugins/imou_life"
)

var imouManagedConfigFields = []string{
	"access_key",
	"secret_key",
	"data_center",
	"authorization_url",
	"public_base_url",
	"callback_secret",
	"event_secret",
	"push_enabled",
	"push_flags",
	"admin_access_token",
	"admin_expires_at",
	"access_token",
	"refresh_token",
	"expires_at",
}

func (h *ImouLifeHandler) loadManagedConfig(ctx context.Context) (*imouStoredConfig, error) {
	if h.pluginManager == nil {
		return nil, errors.New("imou: Plugin Manager is unavailable")
	}
	raw, err := h.pluginManager.GetConfig(ctx, imouIntegrationID)
	if err != nil {
		return nil, err
	}
	var config imouStoredConfig
	if err := json.Unmarshal(raw, &config); err != nil {
		return nil, fmt.Errorf("imou: decode encrypted plugin configuration: %w", err)
	}
	if config.AccessKey == "" || config.SecretKey == "" || config.DataCenter == "" {
		return nil, errors.New("imou: managed project configuration is incomplete")
	}
	if !validHTTPSURL(config.AuthorizationURL, true) {
		return nil, errors.New("imou: authorization_url must be an absolute HTTPS URL")
	}
	if !validHTTPSURL(config.PublicBaseURL, false) {
		return nil, errors.New("imou: public_base_url must be an absolute HTTPS URL without query or fragment")
	}
	base, parseErr := url.Parse(strings.TrimRight(strings.TrimSpace(config.PublicBaseURL), "/"))
	if parseErr != nil || base == nil || base.RawQuery != "" || base.Fragment != "" || base.User != nil {
		return nil, errors.New("imou: public_base_url contains unsupported URL components")
	}

	// The generic plugin catalog accepts the provider's public settings. Private
	// callback capabilities are generated by Domus on first use and persisted
	// atomically, without returning them through the plugin catalog.
	var callbackSecret, eventSecret [32]byte
	if config.CallbackSecret == "" {
		if _, err := rand.Read(callbackSecret[:]); err != nil {
			return nil, fmt.Errorf("imou: generate OAuth callback capability: %w", err)
		}
	}
	if config.EventSecret == "" {
		if _, err := rand.Read(eventSecret[:]); err != nil {
			return nil, fmt.Errorf("imou: generate event callback capability: %w", err)
		}
	}
	if config.CallbackSecret == "" || config.EventSecret == "" {
		callbackValue := config.CallbackSecret
		eventValue := config.EventSecret
		if callbackValue == "" { callbackValue = hex.EncodeToString(callbackSecret[:]) }
		if eventValue == "" { eventValue = hex.EncodeToString(eventSecret[:]) }
		_, err := h.pluginManager.UpdateConfigMutate(ctx, imouIntegrationID, func(current map[string]json.RawMessage) error {
			if imouStoredString(current["callback_secret"]) == "" {
				encoded, _ := json.Marshal(callbackValue)
				current["callback_secret"] = encoded
			}
			if imouStoredString(current["event_secret"]) == "" {
				encoded, _ := json.Marshal(eventValue)
				current["event_secret"] = encoded
			}
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("imou: persist generated callback capabilities: %w", err)
		}
		raw, err = h.pluginManager.GetConfig(ctx, imouIntegrationID)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(raw, &config); err != nil {
			return nil, fmt.Errorf("imou: decode generated callback configuration: %w", err)
		}
	}
	if !validImouCallbackSecret(config.CallbackSecret) || !validImouCallbackSecret(config.EventSecret) {
		return nil, errors.New("imou: stored callback capability is malformed")
	}
	return &config, nil
}

func (h *ImouLifeHandler) saveManagedConfig(ctx context.Context, config imouStoredConfig, status string) error {
	if h.pluginManager == nil {
		return errors.New("imou: Plugin Manager is unavailable")
	}
	encoded, err := json.Marshal(config)
	if err != nil {
		return fmt.Errorf("imou: encode plugin configuration: %w", err)
	}
	var submitted map[string]json.RawMessage
	if err := json.Unmarshal(encoded, &submitted); err != nil {
		return fmt.Errorf("imou: decode plugin configuration: %w", err)
	}

	_, lookupErr := h.pluginManager.GetConfig(ctx, imouIntegrationID)
	switch {
	case errors.Is(lookupErr, integration.ErrIntegrationNotFound):
		if _, err := h.pluginManager.Create(
			ctx,
			imouIntegrationID,
			imou_life.PluginType,
			"Imou Life",
			encoded,
			true,
		); err != nil {
			return fmt.Errorf("imou: create encrypted Plugin Manager instance: %w", err)
		}
	case lookupErr != nil:
		return fmt.Errorf("imou: read existing Plugin Manager configuration: %w", lookupErr)
	default:
		updated, err := h.pluginManager.UpdateConfigMutate(ctx, imouIntegrationID, func(current map[string]json.RawMessage) error {
			for _, key := range imouManagedConfigFields {
				if value, ok := submitted[key]; ok {
					current[key] = append(json.RawMessage(nil), value...)
				} else {
					delete(current, key)
				}
			}
			return nil
		})
		if err != nil {
			return fmt.Errorf("imou: update encrypted Plugin Manager configuration: %w", err)
		}
		if !updated.Enabled {
			if err := h.pluginManager.SetEnabled(ctx, imouIntegrationID, true); err != nil {
				return fmt.Errorf("imou: enable configured Plugin Manager instance: %w", err)
			}
		}
	}

	if err := h.repo.SetStatus(ctx, imouIntegrationID, status, ""); err != nil {
		return fmt.Errorf("imou: update integration status: %w", err)
	}
	return nil
}

func imouStoredString(raw json.RawMessage) string {
	if len(raw) == 0 { return "" }
	var value string
	_ = json.Unmarshal(raw, &value)
	return strings.TrimSpace(value)
}

func validImouCallbackSecret(value string) bool {
	if len(value) != 64 { return false }
	decoded, err := hex.DecodeString(value)
	return err == nil && len(decoded) == 32
}
